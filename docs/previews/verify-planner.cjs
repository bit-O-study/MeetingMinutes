const { chromium } = require('../../../trip/node_modules/@playwright/test');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const source = fs.readFileSync(path.join(__dirname, 'personal-planner.html'));
  const server = http.createServer((req, res) => { res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' }); res.end(source); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    await page.screenshot({ path: path.join(__dirname, 'planner-desktop.png'), fullPage: true });
    await page.locator('.tabs [data-view="tasks"]').click();
    await page.screenshot({ path: path.join(__dirname, 'planner-tasks.png'), fullPage: true });
    await page.locator('#add').click();
    await page.locator('[name="title"]').fill('기간형 검증');
    await page.locator('[name="start"]').fill('2026-10-29');
    await page.locator('[name="end"]').fill('2026-10-27');
    await page.getByRole('button', { name: '미리보기에 추가', exact: true }).click();
    assert.match(await page.locator('#formError').innerText(), /빠를 수/);
    await page.locator('[name="start"]').fill('');
    await page.locator('[name="end"]').fill('2026-10-28');
    await page.getByRole('button', { name: '미리보기에 추가', exact: true }).click();
    assert.match(await page.locator('#taskList').innerText(), /기간형 검증/);
    await page.locator('#add').click();
    await page.locator('[name="title"]').fill('시간 확정 검증');
    await page.locator('[data-mode="fixed"]').click();
    await page.locator('[name="date"]').fill('2026-10-29');
    await page.locator('[name="from"]').fill('14:00');
    await page.locator('[name="to"]').fill('13:00');
    await page.getByRole('button', { name: '미리보기에 추가', exact: true }).click();
    assert.match(await page.locator('#formError').innerText(), /종료 시간/);
    await page.locator('[name="to"]').fill('15:00');
    await page.getByRole('button', { name: '미리보기에 추가', exact: true }).click();
    await page.getByRole('button', { name: '시간 확정 검증 완료', exact: true }).click();
    await page.locator('[data-filter="done"]').click();
    assert.match(await page.locator('#taskList').innerText(), /시간 확정 검증/);
    await page.reload();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(__dirname, 'planner-mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('.mobile-nav [data-view="tasks"]').click();
    await page.locator('#add').click();
    await page.locator('[name="title"]').fill('면접 준비 자료 정리');
    await page.locator('[name="start"]').fill('2026-10-26');
    await page.locator('[name="end"]').fill('2026-10-28');
    await page.screenshot({ path: path.join(__dirname, 'planner-form-mobile.png'), fullPage: true });
    await page.locator('[data-mode="fixed"]').click();
    await page.screenshot({ path: path.join(__dirname, 'planner-fixed-mobile.png'), fullPage: true });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#editor').isVisible(), false);
    await page.setViewportSize({ width: 320, height: 740 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.deepEqual(errors, []);
    console.log('PASS desktop/mobile, tabs, deadline-only creation, date/time validation, completion, modal Escape, 320/390px overflow; screenshots saved.');
  } finally { await browser.close(); server.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
