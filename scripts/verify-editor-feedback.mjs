import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
import { eq } from "drizzle-orm";
import { db, sql } from "../src/lib/db/index.ts";
import { users, spaces, spaceMembers, sessions, notes, noteDocs, noteRevisions } from "../src/lib/db/schema.ts";
const require = createRequire(import.meta.url);
const { chromium, expect: baseExpect } = require(process.env.PLAYWRIGHT_MODULE ?? "@playwright/test");
const expect = baseExpect.configure({ timeout: 20000 });
const base = process.env.EDITOR_TEST_URL ?? "http://127.0.0.1:3306";
const userId = randomUUID(), spaceId = randomUUID(), noteId = randomUUID(), token = randomBytes(32).toString("hex");
const revA = randomUUID(), revB = randomUUID(), photoId = randomUUID();
const doc = (text) => ({ type: "doc", content: [{ type: "paragraph", content: [{ type: "text", text }] }] });
let browser;
try {
  await db.insert(users).values({ id: userId, name: "화면 검증", email: `editor-ux-${userId}@example.invalid` });
  await db.insert(spaces).values({ id: spaceId, name: "모아 편집 화면 검증", ownerId: userId });
  await db.insert(spaceMembers).values({ spaceId, userId, role: "owner" });
  await db.insert(sessions).values({ sessionToken: token, userId, expires: new Date(Date.now() + 900000) });
  await db.insert(notes).values({ id: noteId, spaceId, title: "사진과 회의 기록을 함께 정리하는 긴 제목", template: "blank", content: doc("현재 본문"), createdBy: userId });
  await db.insert(noteDocs).values({ noteId });
  await db.insert(noteRevisions).values([
    { id: revA, noteId, actorId: userId, content: doc("이전 시점 본문"), summary: "이전 메모", createdAt: new Date(Date.now() - 120000) },
    { id: revB, noteId, actorId: userId, content: { type: "doc", content: [...doc("사진이 있는 메모").content, { type: "image", attrs: { src: `/api/attachments/${photoId}`, alt: "회의 사진" } }] }, summary: "사진 추가", createdAt: new Date(Date.now() - 60000) },
  ]);
  browser = await chromium.launch({ channel: "msedge", headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await context.addCookies([{ name: "authjs.session-token", value: token, url: base }]);
  const page = await context.newPage();
  page.setDefaultTimeout(20000);
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.route(`**/api/attachments/${photoId}`, (route) => route.fulfill({ contentType: "image/png", body: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl2Z3sAAAAASUVORK5CYII=", "base64") }));
  await page.goto(`${base}/s/${spaceId}/n/${noteId}`, { waitUntil: "networkidle", timeout: 120000 });
  await page.locator('.tiptap[contenteditable="true"]').waitFor();
  for (const width of [320, 390, 430, 1280]) {
    await page.setViewportSize({ width, height: 844 });
    const toolbar = page.getByTestId("note-toolbar");
    const boxes = await Promise.all(["사진", "이력", "공유"].map(name => toolbar.getByRole("button", { name, exact: true }).boundingBox()));
    assert.ok(boxes.every((b) => b && b.height <= 40 && b.width >= 48));
    assert.ok(Math.max(...boxes.map((b) => b.y)) - Math.min(...boxes.map((b) => b.y)) < 2);
    const connection = await page.getByTestId("note-connection").boundingBox();
    const menu = await page.getByLabel("노트 메뉴").boundingBox();
    assert.ok(connection.y + connection.height <= menu.y + 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "이력", exact: true }).click();
  const history = page.getByRole("complementary", { name: "변경 이력", exact: true });
  await expect(history.getByTestId("revision-preview").getByText("사진이 있는 메모", { exact: true })).toBeVisible();
  await expect(history.getByRole("img", { name: "회의 사진" })).toBeVisible();
  assert.ok((await history.boundingBox()).y < 300);
  const footer = await history.locator("footer").boundingBox();
  const nav = await page.getByRole("navigation", { name: "아래 메뉴" }).boundingBox();
  assert.ok(footer.y + footer.height <= nav.y);
  await db.insert(noteRevisions).values({ noteId, actorId: userId, content: doc("자동 갱신된 시점"), summary: "새 변경 자동 갱신" });
  await expect(history.getByRole("button", { name: /새 변경 자동 갱신/ })).toBeVisible({ timeout: 12000 });
  await history.getByRole("button", { name: /이전 메모/ }).click();
  await expect(history.getByTestId("revision-preview").getByText("이전 시점 본문", { exact: true })).toBeVisible();
  mkdirSync(".verify-shots/editor-feedback", { recursive: true });
  await page.screenshot({ path: ".verify-shots/editor-feedback/history-mobile.png" });
  await context.setOffline(true);
  await history.getByRole("button", { name: "이력 새로고침" }).click();
  await expect(history.getByText("이력을 불러오지 못했습니다.", { exact: false })).toBeVisible();
  await context.setOffline(false);
  await history.getByRole("button", { name: "이력 새로고침" }).click();
  await expect(history.getByText("이력을 불러오지 못했습니다.", { exact: false })).toHaveCount(0);
  await history.getByRole("button", { name: "이력 닫기" }).click();
  await page.getByRole("button", { name: "공유", exact: true }).click();
  await expect(page.getByRole("heading", { name: "공유 링크" })).toBeInViewport();
  await page.getByRole("button", { name: "공유 닫기" }).click();
  console.log("PASS toolbar at 320/390/430/1280px, header status above menu, history image/load/poll/retry, mobile panels");
  await page.goto(`${base}/s/${spaceId}?tab=chat`, { waitUntil: "networkidle" });
  const input = page.getByRole("textbox", { name: "메시지", exact: true });
  const feedback = page.getByTestId("chat-feedback");
  await input.fill("첫 번째 회의 메모");
  await expect(feedback).toHaveText("작성 중…");
  await page.getByRole("button", { name: "전송", exact: true }).click();
  await expect(feedback).toHaveText("메시지를 보냈습니다.");
  await expect(feedback).toHaveCount(0, { timeout: 6000 });
  await input.fill("두 번째 회의 메모");
  await page.getByRole("button", { name: "전송", exact: true }).click();
  await expect(feedback).toHaveText("메시지를 보냈습니다.");
  await input.fill("다음 입력");
  await expect(feedback).toHaveText("작성 중…");
  await page.waitForTimeout(3500);
  await expect(feedback).toHaveText("작성 중…");
  await context.setOffline(true);
  await page.getByRole("button", { name: "전송", exact: true }).click();
  await expect(feedback).toHaveAttribute("role", "alert");
  await page.waitForTimeout(3500);
  await expect(feedback).toBeVisible();
  await expect(input).toHaveValue("다음 입력");
  await context.setOffline(false);
  await page.getByRole("button", { name: "전송", exact: true }).click();
  await expect(feedback).toHaveText("메시지를 보냈습니다.");
  await expect(feedback).toHaveCount(0, { timeout: 6000 });
  await page.screenshot({ path: ".verify-shots/editor-feedback/chat-mobile.png" });
  assert.deepEqual(errors, []);
  console.log("PASS writing/sent/3s dismissal, next draft, persistent error, retry and draft preservation");
} finally {
  await browser?.close();
  // 응답 후 실행되는 접속 기록이 끝난 뒤 임시 사용자와 종속 자료를 정리한다.
  await new Promise(resolve => setTimeout(resolve, 2000));
  await db.delete(spaces).where(eq(spaces.id, spaceId));
  await db.delete(users).where(eq(users.id, userId));
  await sql.end();
  console.log("Temporary test records removed");
}
